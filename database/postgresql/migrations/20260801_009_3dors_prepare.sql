CREATE TABLE IF NOT EXISTS "security_events" (
    "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "event_id" varchar(36) NOT NULL,
    "occurred_at" timestamp without time zone NOT NULL DEFAULT NOW(),
    "actor_id" bigint NULL,
    "action" varchar(120) NOT NULL,
    "resource_type" varchar(80) NULL,
    "resource_id" varchar(128) NULL,
    "request_id" varchar(64) NULL,
    "correlation_id" varchar(64) NULL,
    "instance_id" varchar(80) NULL,
    "ip" varchar(64) NULL,
    "user_agent" text NULL,
    "authentication_level" varchar(32) NOT NULL DEFAULT 'unknown',
    "credential_public_id" varchar(36) NULL,
    "before_state" jsonb NULL,
    "after_state" jsonb NULL,
    "result" varchar(24) NOT NULL,
    "reason" text NULL,
    "risk_level" varchar(16) NOT NULL DEFAULT 'low',
    "metadata" jsonb NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT "uq_security_events_event_id" UNIQUE ("event_id"),
    CONSTRAINT "security_events_result" CHECK ("result" IN ('success', 'failure', 'blocked', 'rejected', 'warning')),
    CONSTRAINT "security_events_risk" CHECK ("risk_level" IN ('low', 'medium', 'high', 'critical')),
    CONSTRAINT "fk_security_events_actor" FOREIGN KEY ("actor_id") REFERENCES "users" ("id") ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS "idx_security_events_actor_time"
ON "security_events" ("actor_id", "occurred_at" DESC);

CREATE INDEX IF NOT EXISTS "idx_security_events_action_time"
ON "security_events" ("action", "occurred_at" DESC);

CREATE TABLE IF NOT EXISTS "security_admin_login_locks" (
    "user_id" bigint PRIMARY KEY,
    "failure_count" integer NOT NULL DEFAULT 0,
    "series_count" integer NOT NULL DEFAULT 0,
    "window_started_at" timestamp without time zone NULL,
    "locked_until" timestamp without time zone NULL,
    "updated_at" timestamp without time zone NOT NULL DEFAULT NOW(),
    CONSTRAINT "security_admin_login_locks_failure_count" CHECK ("failure_count" >= 0),
    CONSTRAINT "security_admin_login_locks_series_count" CHECK ("series_count" >= 0),
    CONSTRAINT "fk_security_admin_login_locks_user" FOREIGN KEY ("user_id") REFERENCES "users" ("id") ON DELETE CASCADE
);
