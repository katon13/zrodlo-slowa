CREATE TABLE IF NOT EXISTS "security_settings" (
    "id" smallint PRIMARY KEY,
    "dors3_mode" varchar(16) NOT NULL DEFAULT 'prepare',
    "fido2_enabled" smallint NOT NULL DEFAULT 0,
    "fido2_required" smallint NOT NULL DEFAULT 0,
    "critical_step_up_method" varchar(16) NOT NULL DEFAULT 'password',
    "physical_approval" varchar(16) NOT NULL DEFAULT 'disabled',
    "admin_idle_timeout_seconds" integer NOT NULL DEFAULT 900,
    "admin_session_max_seconds" integer NOT NULL DEFAULT 28800,
    "step_up_ttl_seconds" integer NOT NULL DEFAULT 300,
    "challenge_ttl_seconds" integer NOT NULL DEFAULT 300,
    "required_gate" jsonb NOT NULL DEFAULT '{}'::jsonb,
    "updated_by" bigint NULL,
    "updated_at" timestamp without time zone NOT NULL DEFAULT NOW(),
    "reason" text NULL,
    CONSTRAINT "security_settings_singleton" CHECK ("id" = 1),
    CONSTRAINT "security_settings_mode" CHECK ("dors3_mode" IN ('prepare', 'test', 'required')),
    CONSTRAINT "security_settings_fido2_enabled" CHECK ("fido2_enabled" IN (0, 1)),
    CONSTRAINT "security_settings_fido2_required" CHECK ("fido2_required" IN (0, 1)),
    CONSTRAINT "security_settings_step_up" CHECK ("critical_step_up_method" IN ('password', 'fido2')),
    CONSTRAINT "security_settings_physical" CHECK ("physical_approval" IN ('disabled', 'enabled')),
    CONSTRAINT "security_settings_idle_range" CHECK ("admin_idle_timeout_seconds" BETWEEN 300 AND 3600),
    CONSTRAINT "security_settings_max_range" CHECK ("admin_session_max_seconds" BETWEEN 3600 AND 86400),
    CONSTRAINT "security_settings_step_up_range" CHECK ("step_up_ttl_seconds" BETWEEN 60 AND 900),
    CONSTRAINT "security_settings_challenge_range" CHECK ("challenge_ttl_seconds" BETWEEN 60 AND 900),
    CONSTRAINT "fk_security_settings_updated_by" FOREIGN KEY ("updated_by") REFERENCES "users" ("id") ON DELETE SET NULL
);

