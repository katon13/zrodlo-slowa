CREATE TABLE IF NOT EXISTS "webauthn_credentials" (
    "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "public_id" varchar(36) NOT NULL,
    "user_id" bigint NOT NULL,
    "credential_id" text NOT NULL,
    "public_key" text NOT NULL,
    "user_handle" varchar(128) NULL,
    "aaguid" varchar(64) NULL,
    "sign_count" bigint NOT NULL DEFAULT 0,
    "transports" jsonb NOT NULL DEFAULT '[]'::jsonb,
    "display_name" varchar(120) NOT NULL,
    "credential_role" varchar(16) NOT NULL DEFAULT 'primary',
    "status" varchar(16) NOT NULL DEFAULT 'active',
    "tested_at" timestamp without time zone NULL,
    "last_used_at" timestamp without time zone NULL,
    "created_by" bigint NULL,
    "created_at" timestamp without time zone NOT NULL DEFAULT NOW(),
    "updated_at" timestamp without time zone NOT NULL DEFAULT NOW(),
    "revoked_by" bigint NULL,
    "revoked_at" timestamp without time zone NULL,
    "revocation_reason" text NULL,
    CONSTRAINT "uq_webauthn_credentials_public_id" UNIQUE ("public_id"),
    CONSTRAINT "uq_webauthn_credentials_credential_id" UNIQUE ("credential_id"),
    CONSTRAINT "webauthn_credentials_role" CHECK ("credential_role" IN ('primary', 'backup')),
    CONSTRAINT "webauthn_credentials_status" CHECK ("status" IN ('active', 'suspended', 'lost', 'revoked')),
    CONSTRAINT "fk_webauthn_credentials_user" FOREIGN KEY ("user_id") REFERENCES "users" ("id") ON DELETE CASCADE,
    CONSTRAINT "fk_webauthn_credentials_created_by" FOREIGN KEY ("created_by") REFERENCES "users" ("id") ON DELETE SET NULL,
    CONSTRAINT "fk_webauthn_credentials_revoked_by" FOREIGN KEY ("revoked_by") REFERENCES "users" ("id") ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS "idx_webauthn_credentials_user_status"
ON "webauthn_credentials" ("user_id", "status");

CREATE TABLE IF NOT EXISTS "webauthn_challenges" (
    "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "public_id" varchar(36) NOT NULL,
    "user_id" bigint NOT NULL,
    "purpose" varchar(24) NOT NULL,
    "challenge_hash" char(64) NOT NULL,
    "action_fingerprint" char(64) NULL,
    "rp_id" varchar(253) NOT NULL,
    "origin" varchar(512) NOT NULL,
    "request_id" varchar(64) NULL,
    "correlation_id" varchar(64) NULL,
    "expires_at" timestamp without time zone NOT NULL,
    "used_at" timestamp without time zone NULL,
    "created_at" timestamp without time zone NOT NULL DEFAULT NOW(),
    CONSTRAINT "uq_webauthn_challenges_public_id" UNIQUE ("public_id"),
    CONSTRAINT "uq_webauthn_challenges_hash" UNIQUE ("challenge_hash"),
    CONSTRAINT "webauthn_challenges_purpose" CHECK ("purpose" IN ('registration', 'authentication', 'step_up', 'test')),
    CONSTRAINT "fk_webauthn_challenges_user" FOREIGN KEY ("user_id") REFERENCES "users" ("id") ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS "idx_webauthn_challenges_expiry"
ON "webauthn_challenges" ("expires_at", "used_at");

CREATE TABLE IF NOT EXISTS "security_recovery_codes" (
    "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "public_id" varchar(36) NOT NULL,
    "user_id" bigint NOT NULL,
    "batch_public_id" varchar(36) NOT NULL,
    "position" smallint NOT NULL,
    "code_hash" varchar(255) NOT NULL,
    "confirmed_at" timestamp without time zone NULL,
    "used_at" timestamp without time zone NULL,
    "used_ip" varchar(64) NULL,
    "created_at" timestamp without time zone NOT NULL DEFAULT NOW(),
    "revoked_at" timestamp without time zone NULL,
    CONSTRAINT "uq_security_recovery_codes_public_id" UNIQUE ("public_id"),
    CONSTRAINT "uq_security_recovery_codes_batch_position" UNIQUE ("user_id", "batch_public_id", "position"),
    CONSTRAINT "security_recovery_codes_position" CHECK ("position" BETWEEN 1 AND 10),
    CONSTRAINT "fk_security_recovery_codes_user" FOREIGN KEY ("user_id") REFERENCES "users" ("id") ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS "idx_security_recovery_codes_user_active"
ON "security_recovery_codes" ("user_id", "used_at", "revoked_at");

